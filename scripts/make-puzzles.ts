// Pre-generates the daily puzzles (two per day) so the server never has to compute them.
// Run (Node 22+):  node --experimental-strip-types scripts/make-puzzles.ts 2026-11-01 2028-12-31
// If you ever change src/generator.ts, run it again: the table must match the generator.
import { writeFileSync } from 'node:fs'
import { dailyLevels, dayNumber, type GeneratedLevel } from '../src/generator.ts'

const from = new Date((process.argv[2] ?? '2026-11-01') + 'T00:00:00Z')
const to = new Date((process.argv[3] ?? '2028-12-31') + 'T00:00:00Z')

const encode = (l: GeneratedLevel) => `${l.creature === 'fire' ? 'f' : 'w'}${l.moves}|${l.rows.join('/')}`

const lines: string[] = []
for (const d = new Date(from); d <= to; d.setUTCDate(d.getUTCDate() + 1)) {
  const day = dayNumber(d)
  const [first, second] = dailyLevels(day)
  lines.push(`  ${day}: ['${encode(first)}', '${encode(second)}'],`)
}

const out = `// GENERATED by scripts/make-puzzles.ts - do not edit by hand.
// day -> [puzzle 1, puzzle 2], each "<f|w><par>|<rows joined by />"  (f = fire / Embi, w = water / Drip)
export const PUZZLE_DATA: Record<number, [string, string]> = {
${lines.join('\n')}
}
`
writeFileSync(new URL('../src/puzzle-data.ts', import.meta.url), out)
console.log(`Wrote ${lines.length} days (${lines.length * 2} puzzles)`)
