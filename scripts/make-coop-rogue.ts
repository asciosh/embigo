// Generates the pool of co-op levels used by the roguelike mode into src/coop-rogue-data.ts
// Run (Node 22+):  node --experimental-strip-types scripts/make-coop-rogue.ts
// Harder than the normal co-op campaign: it starts around the middle of it. Sorted by par.
import { writeFileSync } from 'node:fs'
import { generateCoop, type CoopSpec } from '../src/coop-solver.ts'

type Pair = CoopSpec['roster']
const PAIRS: Pair[] = [['fire', 'water'], ['water', 'air'], ['air', 'fire']]
const LETTER = { fire: 'f', water: 'w', air: 'a' } as const

// two levels for each target par from 14 to 33
const entries: { par: number; line: string }[] = []
let idx = 0
for (let target = 14; target <= 33; target++) {
  for (let k = 0; k < 2; k++, idx++) {
    const roster = PAIRS[idx % 3]
    const w = Math.min(11, 8 + Math.floor((target - 14) / 5))
    const h = Math.min(9, 7 + Math.floor((target - 14) / 8))
    const inner = (w - 2) * (h - 2)
    const spec: CoopSpec = {
      w, h,
      rocks: Math.round(inner * 0.2),
      bushes: Math.min(4, 2 + Math.floor((target - 14) / 8)),
      lakes: Math.min(5, 2 + Math.floor((target - 14) / 6)),
      plates: target >= 17 ? (target >= 24 ? 2 : 1) : 0,
      gates: target >= 17 ? (target >= 24 ? 3 : 2) : 0,
      par: target,
      roster,
      mutual: true,
    }
    let found: { rows: string[]; par: number; mutual: boolean } | null = null
    for (let attempt = 0; attempt < 500 && !found; attempt++) {
      const r = generateCoop(900001 + idx * 100003 + attempt * 7919, spec, 2500)
      if (r && r.par >= target && r.par <= target + 3) found = r
    }
    if (!found) {
      const loose: CoopSpec = { ...spec, mutual: false }
      for (let attempt = 0; attempt < 500 && !found; attempt++) {
        const r = generateCoop(900001 + idx * 100003 + attempt * 7919, loose, 2500)
        if (r && r.par >= target - 1 && r.par <= target + 4) found = r
      }
    }
    if (!found) {
      console.log(`skipped par ${target} (#${k})`)
      continue
    }
    console.log(`rogue ${entries.length + 1}: ${w}x${h} ${roster.join('+')} par ${found.par}${found.mutual ? ' (mutual)' : ' (one-way)'}`)
    entries.push({ par: found.par, line: `  '${LETTER[roster[0]]}${LETTER[roster[1]]}${found.par}|${found.rows.join('/')}',` })
  }
}
entries.sort((a, b) => a.par - b.par)
const out = `// GENERATED by scripts/make-coop-rogue.ts - do not edit by hand.\n// Same format as coop-data.ts, sorted from the shortest to the longest solution.\nexport const COOP_ROGUE_DATA: string[] = [\n${entries.map((e) => e.line).join('\n')}\n]\n`
writeFileSync(new URL('../src/coop-rogue-data.ts', import.meta.url), out)
console.log(`Wrote ${entries.length} roguelike co-op levels`)
