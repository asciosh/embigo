// Generates the co-op campaign levels into src/coop-data.ts
// Run (Node 22+):  node --experimental-strip-types scripts/make-coop.ts
// Every level is checked by a solver: it can be solved, and the two players really need each other.
import { writeFileSync } from 'node:fs'
import { generateCoop, type CoopSpec } from '../src/coop-solver.ts'

type Pair = CoopSpec['roster']
const FW: Pair = ['fire', 'water']
const WA: Pair = ['water', 'air']
const AF: Pair = ['air', 'fire']
const LETTER = { fire: 'f', water: 'w', air: 'a' } as const

// w, h, rocks, bushes, lakes, plates, gates, target par (team moves, passes included), roster
const PLAN: [number, number, number, number, number, number, number, number, Pair][] = [
  [7, 6, 3, 1, 1, 0, 0, 7, FW],
  [7, 6, 3, 2, 2, 0, 0, 9, WA],
  [7, 6, 4, 1, 2, 0, 0, 10, AF],
  [8, 6, 5, 2, 2, 0, 0, 11, FW],
  [8, 7, 5, 2, 2, 1, 1, 11, WA],
  [8, 7, 6, 2, 2, 1, 2, 12, AF],
  [8, 7, 6, 2, 2, 1, 2, 13, FW],
  [9, 7, 7, 2, 3, 1, 2, 14, WA],
  [9, 7, 7, 2, 3, 1, 2, 15, AF],
  [9, 8, 8, 3, 3, 1, 2, 16, FW],
  [9, 8, 8, 3, 3, 1, 2, 17, WA],
  [9, 8, 9, 3, 3, 1, 3, 18, AF],
  [10, 8, 9, 3, 3, 2, 3, 19, FW],
  [10, 8, 10, 3, 3, 2, 3, 20, WA],
  [10, 8, 10, 3, 4, 2, 3, 21, AF],
  [10, 8, 10, 3, 4, 2, 3, 22, FW],
  [10, 9, 11, 3, 4, 2, 3, 23, WA],
  [10, 9, 11, 4, 4, 2, 3, 24, AF],
  [11, 8, 11, 4, 4, 2, 3, 25, FW],
  [11, 8, 12, 4, 4, 2, 3, 26, WA],
  [11, 9, 12, 4, 4, 2, 4, 27, AF],
  [11, 9, 13, 4, 4, 2, 4, 28, FW],
  [11, 9, 13, 4, 5, 2, 4, 29, WA],
  [11, 9, 14, 4, 5, 2, 4, 30, AF],
]

const lines: string[] = []
let mutualCount = 0
PLAN.forEach(([w, h, rocks, bushes, lakes, plates, gates, par, roster], i) => {
  const spec: CoopSpec = { w, h, rocks, bushes, lakes, plates, gates, par, roster, mutual: true }
  let found: { rows: string[]; par: number; mutual: boolean } | null = null
  // try different seeds until the solution length is in the wanted window
  for (let attempt = 0; attempt < 600 && !found; attempt++) {
    const r = generateCoop((i + 1) * 100003 + attempt * 7919, spec, 2500)
    if (r && r.par >= par && r.par <= par + 3) found = r
  }
  if (!found) {
    // relax: accept a level that only one player depends on
    const loose: CoopSpec = { ...spec, mutual: false }
    for (let attempt = 0; attempt < 600 && !found; attempt++) {
      const r = generateCoop((i + 1) * 100003 + attempt * 7919, loose, 2500)
      if (r && r.par >= par && r.par <= par + 3) found = r
    }
  }
  if (!found) throw new Error(`Could not generate co-op level ${i + 1}`)
  if (found.mutual) mutualCount++
  console.log(`level ${i + 1}: ${w}x${h} ${roster.join('+')} par ${found.par}${found.mutual ? ' (mutual)' : ' (one-way)'}`)
  lines.push(`  '${LETTER[roster[0]]}${LETTER[roster[1]]}${found.par}|${found.rows.join('/')}',`)
})

const out = `// GENERATED by scripts/make-coop.ts - do not edit by hand.
// "<creature 1><creature 2><par>|<rows joined by />"  (f = fire / Embi, w = water / Drip, a = air / Zefi)
export const COOP_DATA: string[] = [
${lines.join('\n')}
]
`
writeFileSync(new URL('../src/coop-data.ts', import.meta.url), out)
console.log(`Wrote ${lines.length} co-op levels (${mutualCount} where both players depend on each other)`)
